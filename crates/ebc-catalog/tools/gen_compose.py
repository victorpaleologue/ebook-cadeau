"""Generates crates/ebc-catalog/src/compose_table.rs from Python's unicodedata.

Canonical two-code-point decompositions (starter + combining mark) for the Latin, Greek and
Cyrillic blocks. Facts from the Unicode Character Database; no third-party data file is copied.
"""
import sys, unicodedata

RANGES = [(0x00C0, 0x024F), (0x0370, 0x03FF), (0x0400, 0x04FF), (0x1E00, 0x1EFF), (0x1F00, 0x1FFF)]
rows = []
for lo, hi in RANGES:
    for cp in range(lo, hi + 1):
        ch = chr(cp)
        d = unicodedata.decomposition(ch)
        if not d or d.startswith("<"):
            continue
        parts = [int(p, 16) for p in d.split()]
        if len(parts) != 2:
            continue
        base, mark = parts
        if unicodedata.combining(chr(base)) != 0 or unicodedata.combining(chr(mark)) == 0:
            continue
        # Skip composition exclusions: NFC must give the character back.
        if unicodedata.normalize("NFC", chr(base) + chr(mark)) != ch:
            continue
        rows.append((cp, base, mark))
rows.sort()
out = []
out.append("//! Canonical compositions for Latin, Greek and Cyrillic letters (generated).")
out.append("//!")
out.append("//! Generated by `tools/gen_compose.py` from the Unicode Character Database shipped with")
out.append(f"//! Python {sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}). Do not edit by hand.")
out.append("")
out.append("/// `(composed, base, combining mark)`, sorted by `composed`.")
out.append(f"pub(crate) static COMPOSITIONS: [(char, char, char); {len(rows)}] = [")
for cp, base, mark in rows:
    out.append(f"    ('\\u{{{cp:04X}}}', '\\u{{{base:04X}}}', '\\u{{{mark:04X}}}'),")
out.append("];")
print("\n".join(out))
