#!/usr/bin/env python3
"""Regenerates `src/ranges_data.rs` from an ISBN range snapshot.

Input: the `lib/groups.js` file of the MIT-licensed npm package `isbn3`
(https://github.com/inventaire/isbn3), which is itself generated every month from the
International ISBN Agency's `RangeMessage.xml` (https://www.isbn-international.org/range_file_generation).

The file is treated as *data*: it is tokenised with regular expressions, never evaluated.

Usage:
    python3 -I tools/gen_ranges.py <path/to/groups.js> <source-version> <source-date> > src/ranges_data.rs

Example:
    curl -sSo /tmp/groups.js https://raw.githubusercontent.com/inventaire/isbn3/main/lib/groups.js
    python3 -I tools/gen_ranges.py /tmp/groups.js "isbn3 2.0.13" 2026-11-01 > src/ranges_data.rs
    cargo fmt -p ebc-isbn && cargo test -p ebc-isbn

No network access happens at build time; the generated table is checked in.
"""

import hashlib
import json
import re
import sys


def js_object_to_json(text: str) -> str:
    """Turns the very regular JS object literal of groups.js into JSON, without eval."""
    start = text.index("{")
    end = text.rindex("}")
    body = text[start : end + 1]
    out = []
    pos = 0
    # Single-quoted JS string literals -> JSON strings.
    for m in re.finditer(r"'((?:[^'\\]|\\.)*)'", body):
        out.append(body[pos : m.start()])
        raw = m.group(1)
        value = re.sub(r"\\(.)", lambda e: e.group(1), raw)
        out.append(json.dumps(value, ensure_ascii=False))
        pos = m.end()
    out.append(body[pos:])
    converted = "".join(out)
    # Bare keys `name:` and `ranges:`.
    converted = re.sub(r"(?m)^(\s*)(name|ranges):", r'\1"\2":', converted)
    return converted


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    if len(sys.argv) != 4:
        sys.stderr.write(__doc__)
        return 2
    path, source_version, source_date = sys.argv[1:4]
    with open(path, "rb") as f:
        raw = f.read()
    sha256 = hashlib.sha256(raw).hexdigest()
    groups = json.loads(js_object_to_json(raw.decode("utf-8")))

    rows = []
    for key, value in groups.items():
        m = re.fullmatch(r"(97[89])-(\d{1,7})", key)
        if not m:
            raise SystemExit(f"unexpected group key {key!r}")
        gs1, group = int(m.group(1)), m.group(2)
        name = " ".join(value["name"].split())
        ranges = []
        for lo, hi in value["ranges"]:
            if not (lo.isdigit() and hi.isdigit() and len(lo) == len(hi) and 1 <= len(lo) <= 7):
                raise SystemExit(f"unexpected range {lo!r}-{hi!r} in {key}")
            if int(lo) > int(hi):
                raise SystemExit(f"inverted range {lo!r}-{hi!r} in {key}")
            if len(group) + len(lo) > 8:
                raise SystemExit(f"range {lo!r}-{hi!r} in {key} leaves no publication digit")
            ranges.append((len(lo), int(lo), int(hi)))
        # Sort by position in the registrant number space (7-digit normalised lower bound).
        ranges.sort(key=lambda r: r[1] * 10 ** (7 - r[0]))
        # Merge adjacent ranges of equal length (purely a size optimisation).
        merged = []
        for length, lo, hi in ranges:
            if merged and merged[-1][0] == length and merged[-1][2] + 1 == lo:
                merged[-1] = (length, merged[-1][1], hi)
            else:
                merged.append((length, lo, hi))
        # Reject overlaps.
        prev_end = -1
        for length, lo, hi in merged:
            scale = 10 ** (7 - length)
            if lo * scale <= prev_end:
                raise SystemExit(f"overlapping ranges in {key}")
            prev_end = hi * scale + scale - 1
        rows.append((gs1, len(group), int(group), key, name, merged))

    rows.sort(key=lambda r: (r[0], r[1], r[2]))
    # Group prefixes must be prefix-free, otherwise the group of an ISBN would be ambiguous.
    keys = [(r[0], f"{r[2]:0{r[1]}d}") for r in rows]
    for gs1, g in keys:
        for gs1b, h in keys:
            if gs1 == gs1b and g != h and h.startswith(g):
                raise SystemExit(f"group {gs1}-{g} is a prefix of {gs1b}-{h}")

    n_ranges = sum(len(r[5]) for r in rows)
    w = sys.stdout.write
    w("// @generated by tools/gen_ranges.py — do not edit by hand.\n")
    w("//\n")
    w("// Data: registration groups and registrant ranges of the International ISBN Agency's\n")
    w("// `RangeMessage` (https://www.isbn-international.org/range_file_generation), as vendored by\n")
    w("// the MIT-licensed npm package `isbn3` (https://github.com/inventaire/isbn3, file\n")
    w("// `lib/groups.js`; licence text in `NOTICE-isbn3.txt` next to this crate's manifest).\n")
    w(f"// Source snapshot: {source_version}, published {source_date}.\n")
    w(f"// SHA-256 of the input file: {sha256}\n")
    w(f"// {len(rows)} registration groups, {n_ranges} registrant ranges (adjacent ranges of equal\n")
    w("// registrant length are merged; unassigned ranges are absent).\n")
    w("\n")
    w("use crate::ranges::{Group, g, r};\n")
    w("\n")
    w(f"/// Date of the range data snapshot (ISO 8601).\n")
    w(f"pub(crate) const RANGE_DATA_DATE: &str = {rust_str(source_date)};\n")
    w("\n")
    w(f"/// Where the range data snapshot comes from.\n")
    w(f"pub(crate) const RANGE_DATA_SOURCE: &str = {rust_str(source_version)};\n")
    w("\n")
    w("/// Registration groups sorted by (GS1 prefix, group length, group number).\n")
    w("#[rustfmt::skip]\n")
    w(f"pub(crate) static GROUPS: [Group; {len(rows)}] = [\n")
    for gs1, glen, group, key, name, ranges in rows:
        rs = ", ".join(f"r({length}, {lo}, {hi})" for length, lo, hi in ranges)
        w(f"    g({gs1}, {glen}, {group}, {rust_str(key)}, {rust_str(name)}, &[{rs}]),\n")
    w("];\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
