/// Every glyph's outline in font units, one line per glyph, and the number of segments.
fn outline_listing(font: &Font) -> (String, usize) {
    let size = unit_size(font);
    let scale = font.metrics().mm_per_unit(size);
    let mut listing = String::new();
    let mut segments = 0;
    for id in 0..font.glyph_count() {
        let glyph = ShapedGlyph { id, x: 0.0, y: 0.0, advance: 0.0, text: String::new() };
        let run = ShapedText { glyphs: vec![glyph], width: 0.0, size_pt: size };
        let path = run.try_to_outline(font, Point::new(0.0, 0.0)).expect("an ordinary glyph");
        segments += path.segs.len();
        let _ = write!(listing, "G{id}");
        for seg in &path.segs {
            let p = |p: &Point| format!("{:.3},{:.3}", p.x / scale, -p.y / scale + 0.0);
            let _ = match seg {
                PathSeg::MoveTo(a) => write!(listing, " M{}", p(a)),
                PathSeg::LineTo(a) => write!(listing, " L{}", p(a)),
                PathSeg::QuadTo(a, b) => write!(listing, " Q{} {}", p(a), p(b)),
                PathSeg::CubicTo(a, b, c) => write!(listing, " C{} {} {}", p(a), p(b), p(c)),
                PathSeg::Close => write!(listing, " Z"),
            };
        }
        listing.push('\n');
    }
    (listing, segments)
}

