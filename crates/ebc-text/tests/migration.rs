#[test]
fn outlines_of_every_bundled_glyph_are_those_of_the_previous_font_stack() {
    for &(label, bytes, glyphs, segments, fingerprint, ..) in FONTS {
        let font = common::font(bytes);
        assert_eq!(font.glyph_count(), glyphs, "{label}");
        let (listing, total) = outline_listing(&font);
        assert_eq!(total, segments, "{label}: number of path segments");
        assert_eq!(fnv(listing.as_bytes()), fingerprint, "{label}: outline fingerprint");
    }
}

#[test]
fn character_maps_and_metrics_are_those_of_the_previous_font_stack() {
    for &(label, bytes, _, _, _, mapped, fingerprint, metrics) in FONTS {
        let font = common::font(bytes);
        let mut listing = String::new();
        let mut count = 0u32;
        for c in (0..0x3_0000u32).filter_map(char::from_u32) {
            if let Some(glyph) = font.glyph_id(c) {
                let _ = write!(listing, "{:x}:{glyph} ", c as u32);
                count += 1;
            }
        }
        assert_eq!(count, mapped, "{label}: mapped characters");
        assert_eq!(fnv(listing.as_bytes()), fingerprint, "{label}: character map fingerprint");
        assert_eq!(format!("{:?}", font.metrics()), metrics, "{label}");
    }
}

