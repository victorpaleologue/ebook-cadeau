//! The font-stack migration (`ttf-parser` + `rustybuzz` → `read-fonts` + `harfrust`) must
//! not change what the crate produces. The constants below were recorded with the old
//! stack, immediately before the migration, on the bundled fonts:
//!
//! * shaped runs — glyph ids, positions and advances in font units — for French text with
//!   ligatures, kerning, accents (precomposed and combining), letter spacing, small caps,
//!   old-style figures, a right-to-left run and characters the fonts lack;
//! * a fingerprint of the outline of **every** glyph of every bundled font (coordinates
//!   to 1/1000 of a font unit), and of the complete character map (U+0000..U+2FFFF);
//! * the global metrics.
//!
//! A change of any of these values is a change of behaviour: look at it before updating
//! the constant.
//!
//! What is known to differ from the old stack, none of it on the bundled fonts with the
//! exception of the first point (compared on 12 more font files, 39 350 glyphs):
//!
//! * a run forced right-to-left that contains no letter at all (digits, punctuation) is
//!   kerned in reading order, as HarfBuzz does; `rustybuzz` kerned it in reverse;
//! * `kern = 0` on Hebrew or Arabic text no longer reverses the run (a `rustybuzz` quirk);
//! * TrueType outlines are placed like FreeType and HarfBuzz place them — moved
//!   horizontally where a glyph's left side bearing in `hmtx` differs from its `xMin`;
//! * coordinates the font library computes (scaled or rotated components, instances of
//!   variable fonts) are rounded to 1/64 of a font unit;
//! * the accent of a PostScript `seac` composition is drawn before its base glyph.
