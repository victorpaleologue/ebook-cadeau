/// FNV-1a, 64 bits.
fn fnv(bytes: &[u8]) -> u64 {
    bytes
        .iter()
        .fold(0xcbf2_9ce4_8422_2325u64, |h, &b| (h ^ u64::from(b)).wrapping_mul(0x100_0000_01b3))
}

/// A size at which one font unit is one millimetre.
fn unit_size(font: &Font) -> f64 {
    f64::from(font.metrics().units_per_em) / MM_PER_PT
}

fn options(name: &str) -> ShapeOptions {
    let d = ShapeOptions::default();
    let feature = |tag: &str, value: u32| (tag.to_owned(), value);
    match name {
        "default" => d,
        "spaced" => ShapeOptions { letter_spacing_em: 0.125, ..d },
        "tight" => ShapeOptions { letter_spacing_em: -0.0625, ..d },
        "rtl" => ShapeOptions { rtl: true, ..d },
        "tr" => ShapeOptions { language: Some("tr".into()), ..d },
        "noliga" => ShapeOptions { features: vec![feature("liga", 0)], ..d },
        "nokern" => ShapeOptions { features: vec![feature("kern", 0)], ..d },
        "smcp" => ShapeOptions { features: vec![feature("smcp", 1)], ..d },
        "onum" => ShapeOptions { features: vec![feature("onum", 1), feature("dlig", 1)], ..d },
        other => panic!("unknown option set {other}"),
    }
}

/// A shaped run in font units: `width: id@x,y+advance"text" …`.
fn describe(font: &Font, text: &str, opts: &ShapeOptions) -> String {
    let size = unit_size(font);
    let scale = font.metrics().mm_per_unit(size);
    let run = shape(font, text, size, opts);
    let mut out = format!("w={:.4}:", run.width / scale);
    for g in &run.glyphs {
        let (x, y, advance) = (g.x / scale, g.y / scale, g.advance / scale);
        let _ = write!(out, " {}@{x:.4},{y:.4}+{advance:.4}{:?}", g.id, g.text);
    }
    out
}

